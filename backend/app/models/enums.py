    STUDENT = "STUDENT"
    FACULTY = "FACULTY"
    DEPARTMENT_ADMIN = "DEPARTMENT_ADMIN"
    RESOURCE_MANAGER = "RESOURCE_MANAGER"
    SYSTEM_ADMIN = "SYSTEM_ADMIN"

